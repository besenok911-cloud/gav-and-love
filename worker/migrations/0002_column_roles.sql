-- Ролі колонок прайсу, рівень майстра і зафіксована тривалість візиту.
--
-- Навіщо. Прайс салону — це таблиця, і досі код здогадувався про значення її колонок за
-- місцем: ціна — остання комірка, вага — друга. Другому салону це не підходить: у нього дві
-- ціни в рядку (звичайний грумер і топ-грумер, різниця від 0 до 500 ₴ і непропорційна) та
-- своя тривалість на кожну породу (23 різних значення, від «10 хв» до «5 г»).
--
-- Три ADD COLUMN, жодної пересборки таблиці — на відміну від 0001, де чотири таблиці
-- довелося перебудовувати. Існуючі рядки отримують NULL, а NULL означає «як було»:
-- поки col_roles порожній, ціна читається з останньої комірки, як і сьогодні.

-- Що означає кожна колонка прайсу. JSON-масив, паралельний columns:
--   "label"       — порода або назва варіанта (перша комірка сьогодні)
--   "weight"      — вага, лише щоб розрізнити однойменні рядки
--   "price"       — ціна, єдиний рівень
--   "price:<key>" — ціна рівня <key>, напр. price:base / price:top; порядок колонок = порядок рівнів
--   "duration"    — тривалість цього рядка, «1 г 45 хв» або число хвилин
--   "info" / ""   — довідкова колонка, у розрахунках не бере участі
ALTER TABLE services ADD COLUMN col_roles TEXT;

-- Ключ цінового рівня майстра: "base", "top", NULL. Саме КЛЮЧ, а не заголовок колонки —
-- інакше перейменування «Топ-грумер» у CRM тихо обнулило б рівень усіх майстрів.
-- Людяна назва живе в columns[i], і це єдине джерело правди.
ALTER TABLE masters ADD COLUMN tier TEXT;

-- Скільки хвилин фактично зайняв візит. Тривалість візиту — це факт, а не функція сьогоднішнього
-- прайсу: рядок можуть видалити, породу перейменувати, час виправити заднім числом. Без цього
-- будь-яка правка прайсу мовчки зсувала б зайнятість усіх минулих візитів.
ALTER TABLE bookings ADD COLUMN duration INTEGER;
