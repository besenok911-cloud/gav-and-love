// Тривалість у людяному форматі: 90 -> "1 год 30 хв"
window.GL_FMT_DUR = function (min) {
  min = +min || 0; if (!min) return "";
  var h = Math.floor(min / 60), m = min % 60;
  return (h ? h + " год" : "") + (h && m ? " " : "") + (m ? m + " хв" : "");
};
